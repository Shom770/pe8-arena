// Prepares public/ for deployment:
//  1. copies the in-browser OCaml toplevel out of node_modules into public/ocaml/
//  2. copies problems.json into public/
//  3. vendors CodeMirror 5 and bundles the Supabase client into public/vendor/
//  4. writes public/config.js from environment variables
import { build } from 'esbuild';
import { cp, mkdir, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const pub = path.join(root, 'public');

const pkgDir = path.join(root, 'node_modules', '@live-codes', 'ocaml');
const assets = path.join(pkgDir, 'assets', 'interpreter');
if (!existsSync(assets)) throw new Error(`OCaml interpreter assets not found at ${assets}`);
await rm(path.join(pub, 'ocaml'), { recursive: true, force: true });
await mkdir(path.join(pub, 'ocaml'), { recursive: true });
await cp(assets, path.join(pub, 'ocaml'), { recursive: true });
console.log('copied OCaml toplevel to public/ocaml');

await cp(path.join(root, 'problems.json'), path.join(pub, 'problems.json'));
console.log('copied problems.json');

const vendor = path.join(pub, 'vendor');
await rm(vendor, { recursive: true, force: true });
const cmDir = path.join(root, 'node_modules', 'codemirror');
const cmOut = path.join(vendor, 'codemirror');
await mkdir(path.join(cmOut, 'mode'), { recursive: true });
await cp(path.join(cmDir, 'lib'), path.join(cmOut, 'lib'), { recursive: true });
await cp(path.join(cmDir, 'mode', 'mllike'), path.join(cmOut, 'mode', 'mllike'), { recursive: true });
await cp(path.join(cmDir, 'addon', 'edit'), path.join(cmOut, 'addon', 'edit'), { recursive: true });
console.log('vendored CodeMirror');

await build({
  stdin: { contents: "export { createClient } from '@supabase/supabase-js';", resolveDir: root, loader: 'js' },
  bundle: true,
  format: 'esm',
  platform: 'browser',
  minify: true,
  outfile: path.join(vendor, 'supabase.js'),
  logLevel: 'warning',
});
console.log('bundled Supabase client');

// Local dev: pick up variables from .env.local / .env. Vercel sets them directly, and
// values already in the environment win over the files.
for (const file of ['.env.local', '.env']) {
  if (existsSync(path.join(root, file))) process.loadEnvFile(path.join(root, file));
}

const env = process.env;
const config = {
  supabaseUrl: env.SUPABASE_URL || env.NEXT_PUBLIC_SUPABASE_URL || '',
  supabaseAnonKey: env.SUPABASE_ANON_KEY || env.NEXT_PUBLIC_SUPABASE_ANON_KEY || env.SUPABASE_PUBLISHABLE_KEY || '',
  stressN: Number(env.ARENA_STRESS_N) || 20000,
  gradeTimeoutSeconds: Number(env.ARENA_GRADE_TIMEOUT) || 15,
};
await writeFile(
  path.join(pub, 'config.js'),
  `// Generated by scripts/build.mjs. Edit environment variables, not this file.\nwindow.ARENA_CONFIG = ${JSON.stringify(config, null, 2)};\n`
);
console.log(`wrote public/config.js (${config.supabaseUrl ? 'Supabase realtime' : 'local mode: no Supabase variables set'})`);
